#!/usr/bin/env python3
"""
Builds results/summary.md and results/before-after.png from results/timings.csv.
Uses the latest measurement for each (phase, query) pair.
    python3 report.py
"""
import csv
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.ticker import FuncFormatter

HERE = Path(__file__).resolve().parent
rows = list(csv.DictReader((HERE / "results" / "timings.csv").open(encoding="utf-8")))
t = {(r["phase"], r["query"]): float(r["median_ms"]) for r in rows}   # latest wins

# label, query in "before", query/phase used for the final measurement, technique
LINES = [
    ("Q1 Customer history",           "q1_customer_history",          ("after-indexes",  "q1_customer_history"),            "Composite index (customer_id, order_date DESC)"),
    ("Q2 Outstanding balances",       "q2_outstanding",               ("after-redesign", "q2b_outstanding_stored_balance"), "Stored amount_paid + partial index"),
    ("Q3 Production board",           "q3_production_board",          ("after-indexes",  "q3_production_board"),            "Partial index on open orders"),
    ("Q4 Monthly revenue",            "q4_monthly_revenue",           ("after-redesign", "q4b_monthly_revenue_summary"),    "Materialised summary view"),
    ("Q5 Stuck orders (correlated)",  "q5a_stuck_orders_correlated",  ("after-indexes",  "q5a_stuck_orders_correlated"),    "Index (order_id, changed_at DESC)"),
    ("Q5 Stuck orders (NOT EXISTS)",  "q5b_stuck_orders_not_exists",  ("after-indexes",  "q5b_stuck_orders_not_exists"),    "Rewrite to anti-join + same index"),
    ("Q6 Reorder report",             "q6_reorder_report",            ("after-indexes",  "q6_reorder_report"),              "Index (material_id, moved_at)"),
    ("Q7 Record a payment (write)",   "q7_record_payment",            ("after-redesign", "q7_record_payment"),              "FK index on payment(invoice_id); trigger replaced by CHECK"),
]

def fmt(ms):
    return f"{ms:,.0f} ms" if ms >= 100 else (f"{ms:.1f} ms" if ms >= 1 else f"{ms:.2f} ms")

def speedup(x):
    return f"{x:,.0f}×" if x >= 10 else f"{x:.1f}×"

# ---- summary table ------------------------------------------------------
md = ["| Query | Before | After indexes | After redesign | Speed-up | Technique |",
      "|---|---|---|---|---|---|"]
data = []
for label, q, final, tech in LINES:
    before = t[("before", q)]
    idx = t.get(("after-indexes", q))
    red = t.get(final) if final[0] == "after-redesign" else None
    best = t[final]
    data.append((label, before, best))
    md.append(f"| {label} | {fmt(before)} | {fmt(idx) if idx else '—'} | "
              f"{fmt(red) if red else '—'} | **{speedup(before / best)}** | {tech} |")
(HERE / "results" / "summary.md").write_text(
    "# Performance Summary\n\nMedian of 5 warm-cache runs. "
    "Generated by `report.py` from `timings.csv`.\n\n" + "\n".join(md) + "\n", encoding="utf-8")

# ---- dumbbell chart (log scale) -----------------------------------------
BEFORE, AFTER = "#eb6834", "#2a78d6"     # categorical slots 2 and 1 (validated pair)
INK, MUTED, GRID, SURFACE = "#0b0b0b", "#52514e", "#e4e3df", "#fcfcfb"

fig, ax = plt.subplots(figsize=(10, 5.4), dpi=160)
fig.patch.set_facecolor(SURFACE); ax.set_facecolor(SURFACE)
ys = list(range(len(data)))[::-1]
for y, (label, b, a) in zip(ys, data):
    ax.plot([a, b], [y, y], color=GRID, linewidth=2, zorder=1, solid_capstyle="round")
    ax.scatter([b], [y], s=70, color=BEFORE, edgecolor=SURFACE, linewidth=2, zorder=3)
    ax.scatter([a], [y], s=70, color=AFTER,  edgecolor=SURFACE, linewidth=2, zorder=3)
    ax.text(b * 1.25, y, fmt(b), va="center", ha="left", fontsize=8.5, color=MUTED)
    ax.text(a / 1.25, y, fmt(a), va="center", ha="right", fontsize=8.5, color=MUTED)

ax.set_xscale("log")
ax.set_xlim(0.03, 100000)
ax.xaxis.set_major_formatter(FuncFormatter(lambda v, _: f"{v:g} ms"))
ax.set_yticks(ys, [d[0] for d in data], fontsize=9.5, color=INK)
ax.tick_params(axis="x", colors=MUTED, labelsize=8.5)
ax.tick_params(axis="y", length=0)
ax.grid(axis="x", color=GRID, linewidth=0.8); ax.set_axisbelow(True)
for s in ax.spines.values(): s.set_visible(False)
ax.scatter([], [], s=70, color=BEFORE, label="Before (no extra indexes)")
ax.scatter([], [], s=70, color=AFTER,  label="After optimisation")
ax.legend(loc="lower right", frameon=False, fontsize=9, labelcolor=INK)
ax.set_title("StitchLine query execution time, before vs after optimisation (log scale)",
             loc="left", fontsize=11.5, color=INK, pad=12)
fig.tight_layout()
fig.savefig(HERE / "results" / "before-after.png", facecolor=SURFACE)
print((HERE / "results" / "summary.md").read_text(encoding="utf-8"))
